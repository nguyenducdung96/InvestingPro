"""Read the public QNI position board; never infer arrivals/departures from it."""
import datetime as dt
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'http://cangvuhanghaiqni.gov.vn/tivi.aspx'
VERSION = 'dungquat-position-html/1.0.0'
HEADERS = ['TT', 'TÊN TÀU', 'Q/TỊCH', 'LOẠI TÀU', 'GT', 'DWT', 'LOA', 'ĐẠI LÝ', 'HÀNG HÓA', 'VỊ TRÍ', 'THỜI GIAN']


class Rows(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []
        self.rows = []

    def handle_starttag(self, tag, attrs):
        if tag == 'tr':
            self.stack.append({'cells': [], 'text': None, 'nested': False})
            if len(self.stack) > 1:
                self.stack[-2]['nested'] = True
        elif tag in ('td', 'th') and self.stack:
            self.stack[-1]['text'] = []

    def handle_data(self, data):
        if self.stack and self.stack[-1]['text'] is not None:
            self.stack[-1]['text'].append(data)

    def handle_endtag(self, tag):
        if not self.stack:
            return
        row = self.stack[-1]
        if tag in ('td', 'th') and row['text'] is not None:
            row['cells'].append(' '.join(' '.join(row['text']).split()))
            row['text'] = None
        elif tag == 'tr':
            self.stack.pop()
            if not row['nested']:
                self.rows.append(row['cells'])


def weight(raw):
    # Source uses dot thousands and comma decimals. Reject ambiguous formats.
    if not re.fullmatch(r'(?:\d{1,3}(?:\.\d{3})+|\d+)(?:,\d+)?', raw):
        return None
    value = float(raw.replace('.', '').replace(',', '.'))
    return value if value > 0 else None


def parse(raw):
    page = Rows()
    page.feed(raw.decode('utf-8-sig', errors='strict'))
    headers = [i for i, row in enumerate(page.rows) if row == HEADERS]
    if len(headers) != 1:
        raise ValueError('Position board header changed or ambiguous')
    rows = [row for row in page.rows[headers[0] + 1:] if any(row)]
    if not rows or any(len(row) != 11 or not re.fullmatch(r'\d+\.', row[0]) for row in rows):
        raise ValueError('Position board rows changed')
    selected = []
    for row in rows:
        # Agency GMD does not prove berth GMD. ETA is a separate location.
        if row[9].strip().upper() != 'GMD':
            continue
        if not row[1]:
            raise ValueError('Missing vessel name')
        selected.append({'source_row': int(row[0][:-1]), 'vessel': row[1],
                         'dwt': weight(row[5]), 'gt': weight(row[4]),
                         'position': row[9], 'source_time_raw': row[10], 'raw': row})
    return {'source_rows': len(rows), 'excluded_rows': len(rows) - len(selected), 'observations': selected}


def main():
    folder = ROOT / '.local/dungquat'
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / 'download.html'
    # curl validates HTTPS if the public HTTP endpoint redirects to HTTPS.
    result = subprocess.run(['curl.exe', '--fail', '--silent', '--show-error', '--location',
                             '--max-redirs', '3', '--max-time', '30', '--max-filesize', '4000000',
                             SOURCE, '-o', str(target)], capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(result.stderr.strip())
    raw = target.read_bytes()
    parsed = parse(raw)  # Do not replace the last accepted export on schema failure.
    digest = hashlib.sha256(raw).hexdigest()
    archive = folder / 'archive'
    archive.mkdir(exist_ok=True)
    (archive / (digest + '.html')).write_bytes(raw)
    data = {'ticker': 'GMD', 'asset': 'gemadept_dung_quat', 'semantics': 'authority_position_snapshot',
            'source_url': SOURCE, 'checked_at': dt.datetime.now(dt.timezone.utc).isoformat(),
            'source_sha256': digest, 'parser_version': VERSION, 'history_complete': False,
            'actual_verified': False, 'arrivals': None, 'departures': None, **parsed}
    output = ROOT / 'packages/modules/port/src/dungquat-snapshot-data.ts'
    output.write_text('// Generated by scripts/collect-dungquat-snapshot.py.\nexport const dungquatSnapshot = '
                      + json.dumps(data, ensure_ascii=False, indent=2) + ' as const;\n', encoding='utf-8')
    print(json.dumps({'sha256': digest, 'source_rows': parsed['source_rows'],
                      'selected_rows': len(parsed['observations'])}))


if __name__ == '__main__':
    main()
